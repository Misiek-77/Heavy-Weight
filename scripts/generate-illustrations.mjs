/**
 * Generates the exercise illustrations in public/exercises with the Gemini image API.
 *
 *   npm run illustrations                      missing illustrations only
 *   npm run illustrations -- squat deadlift    just these (regenerates them if they exist)
 *   npm run illustrations -- --all             regenerate everything
 *   npm run illustrations -- --dry-run         print the prompts, call nothing
 *   npm run illustrations -- --manifest        only rebuild src/ui/illustrated.ts from the files on disk
 *
 * Needs GEMINI_API_KEY in the environment. GEMINI_IMAGE_MODEL overrides the model.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { POSES, promptFor } from './illustration-poses.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'public', 'exercises');
const MANIFEST = join(ROOT, 'src', 'ui', 'illustrated.ts');
const MODEL = process.env.GEMINI_IMAGE_MODEL || 'gemini-nano-banana-2.1';
const ENDPOINT = `https://generativelanguage.googleapis.com/v1beta/models/${MODEL}:generateContent`;
/** An existing illustration sent along with every prompt so the whole set shares one style. */
const STYLE_REFERENCE = join(OUT_DIR, 'incline-db-press.jpg');
const WIDTH = 960;
const HEIGHT = 717;
const CONCURRENCY = 3;
const ATTEMPTS = 4;

const args = process.argv.slice(2);
const flags = new Set(args.filter((a) => a.startsWith('--')));
const named = args.filter((a) => !a.startsWith('--'));

const outFile = (key) => join(OUT_DIR, `${key}.jpg`);
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

/** Rewrites the list of illustrated exercises the app reads, from the files actually on disk. */
function writeManifest() {
  const keys = readdirSync(OUT_DIR)
    .filter((f) => f.endsWith('.jpg'))
    .map((f) => f.slice(0, -4))
    .filter((k) => k in POSES)
    .sort();
  const framesDir = join(OUT_DIR, 'frames');
  const animated = (existsSync(framesDir) ? readdirSync(framesDir) : [])
    .filter((f) => f.endsWith('.jpg'))
    .map((f) => f.slice(0, -4))
    .filter((k) => keys.includes(k))
    .sort();
  const musclesDir = join(OUT_DIR, 'muscles');
  const muscles = (existsSync(musclesDir) ? readdirSync(musclesDir) : [])
    .filter((f) => f.endsWith('.jpg'))
    .map((f) => f.slice(0, -4))
    .filter((k) => k in POSES)
    .sort();
  const list = (items) => items.map((k) => `  '${k}',`).join('\n');
  const lines = list(keys);
  writeFileSync(
    MANIFEST,
    `// Generated by scripts/generate-illustrations.mjs from public/exercises. Do not edit by hand.\n` +
      `/** Built-in exercises (id without the \`seed-\` prefix) that have an illustration in public/exercises. */\n` +
      `export const ILLUSTRATED: ReadonlySet<string> = new Set([\n${lines}\n]);\n\n` +
      `/** Those that also have a four-frame animation strip in public/exercises/frames. */\n` +
      `export const ANIMATED: ReadonlySet<string> = new Set([${animated.length ? `\n${list(animated)}\n` : ''}]);\n\n` +
      `/** Those that have a muscle chart in public/exercises/muscles. */\n` +
      `export const MUSCLE_CHARTS: ReadonlySet<string> = new Set([${muscles.length ? `\n${list(muscles)}\n` : ''}]);\n`,
  );
  return keys.length;
}

/** An error that will not go away on retry (bad key, unknown model, billing), so the whole run should stop. */
class FatalError extends Error {}

async function requestImage(key, apiKey, reference) {
  const parts = [{ text: promptFor(key) }];
  if (reference) {
    parts[0].text +=
      ' Match the drawing style, colours, line weight and background of the attached reference image exactly,' +
      ' but draw the exercise described here, not the one in the reference.';
    parts.push({ inline_data: { mime_type: 'image/jpeg', data: reference } });
  }
  const body = {
    contents: [{ parts }],
    generationConfig: { responseModalities: ['TEXT', 'IMAGE'], imageConfig: { aspectRatio: '4:3', imageSize: '1K' } },
  };

  for (let attempt = 1; ; attempt++) {
    let res;
    try {
      res = await fetch(ENDPOINT, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'x-goog-api-key': apiKey },
        body: JSON.stringify(body),
      });
    } catch (error) {
      if (attempt >= ATTEMPTS) throw new Error(`network error: ${error.message}`);
      await sleep(2000 * 2 ** attempt);
      continue;
    }

    if (res.ok) {
      const json = await res.json();
      const image = json.candidates?.[0]?.content?.parts?.find((p) => (p.inlineData ?? p.inline_data)?.data && !p.thought);
      if (image) return Buffer.from((image.inlineData ?? image.inline_data).data, 'base64');
      const reason = json.candidates?.[0]?.finishReason ?? json.promptFeedback?.blockReason ?? 'no image in the response';
      if (attempt >= ATTEMPTS) throw new Error(`no image returned (${reason})`);
      continue;
    }

    const text = (await res.text()).slice(0, 400);
    const retryable = res.status === 429 || res.status >= 500;
    if (!retryable) throw new FatalError(`HTTP ${res.status} from the Gemini API: ${text}`);
    if (attempt >= ATTEMPTS) throw new Error(`HTTP ${res.status} after ${ATTEMPTS} attempts: ${text}`);
    await sleep(5000 * 2 ** attempt);
  }
}

/** Crops to 4:3-ish, scales down and re-encodes so each file stays small enough to precache offline. */
async function toJpeg(buffer) {
  const { Jimp } = await import('jimp');
  const image = await Jimp.fromBuffer(buffer);
  image.cover({ w: WIDTH, h: HEIGHT });
  return image.getBuffer('image/jpeg', { quality: 84 });
}

async function main() {
  mkdirSync(OUT_DIR, { recursive: true });

  if (flags.has('--manifest')) {
    console.log(`Manifest: ${writeManifest()} illustrations.`);
    return;
  }

  const unknown = named.filter((k) => !(k in POSES));
  if (unknown.length) throw new FatalError(`Unknown exercise id: ${unknown.join(', ')}`);

  const todo = named.length
    ? named
    : Object.keys(POSES).filter((k) => flags.has('--all') || !existsSync(outFile(k)));

  if (flags.has('--dry-run')) {
    for (const key of todo) console.log(`\n[${key}]\n${promptFor(key)}`);
    console.log(`\n${todo.length} illustrations would be generated with ${MODEL}.`);
    return;
  }
  if (!todo.length) {
    console.log(`Nothing to do, every exercise has an illustration. Manifest: ${writeManifest()}.`);
    return;
  }

  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) throw new FatalError('GEMINI_API_KEY is not set. Create a key in Google AI Studio and set it in this terminal first.');

  const reference = existsSync(STYLE_REFERENCE) ? readFileSync(STYLE_REFERENCE).toString('base64') : null;
  console.log(`Generating ${todo.length} illustrations with ${MODEL}...`);

  const queue = [...todo];
  const failed = [];
  let fatal = null;
  let done = 0;

  async function worker() {
    while (queue.length && !fatal) {
      const key = queue.shift();
      try {
        // The reference itself is regenerated without a reference, so it never copies its own flaws.
        const png = await requestImage(key, apiKey, outFile(key) === STYLE_REFERENCE ? null : reference);
        writeFileSync(outFile(key), await toJpeg(png));
        console.log(`  ok    ${key}  (${++done}/${todo.length})`);
      } catch (error) {
        if (error instanceof FatalError) fatal = error;
        else {
          failed.push(key);
          console.log(`  FAIL  ${key}: ${error.message}`);
        }
      }
    }
  }
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));

  console.log(`Manifest: ${writeManifest()} illustrations.`);
  if (fatal) throw fatal;
  if (failed.length) {
    console.log(`\n${failed.length} failed. Run again to retry them:\n  npm run illustrations -- ${failed.join(' ')}`);
    process.exitCode = 1;
  } else {
    console.log('Done.');
  }
}

main().catch((error) => {
  console.error(`\n${error.message}`);
  process.exitCode = 1;
});
